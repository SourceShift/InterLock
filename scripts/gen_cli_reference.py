"""Regenerate docs/reference/cli.md from the `interlock` command's own parsers.

    python scripts/gen_cli_reference.py          # rewrite the page
    python scripts/gen_cli_reference.py --check  # exit 1 if the page is stale

Each command's module docstring and argparse definitions are the source, so
the reference can't drift from `--help`.
"""
from __future__ import annotations

import argparse
import importlib
import io
import os
import re
import sys
from pathlib import Path
from typing import List

# argparse wraps usage to the terminal width; pin it so the page is stable.
os.environ["COLUMNS"] = "100"

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from interlock.cli import COMMANDS, build_parser  # noqa: E402

OUT = ROOT / "docs" / "reference" / "cli.md"


def _fence_examples(text: str) -> List[str]:
    out: List[str] = []
    block: List[str] = []
    for line in text.split("\n"):
        if re.match(r"^  \S", line) or (block and line.startswith("  ") and line.strip()):
            block.append(line[2:])
            continue
        if block:
            out += ["```bash"] + block + ["```"]
            block = []
        out.append(line)
    if block:
        out += ["```bash"] + block + ["```"]
    return out


def render() -> str:
    parser = build_parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    out = ["# Command line", "",
           "<!-- Generated by scripts/gen_cli_reference.py. Do not edit by hand. -->", "",
           "`interlock` (also `python -m interlock`) is installed with the package. Each",
           "command's `--help` shows the same text as below. `--no-color` (before the",
           "command) turns off color; color is also off when output isn't a terminal or",
           "`NO_COLOR` is set.", "", "| Command | Does |", "|---|---|"]
    out += ["| [`{0}`](#interlock-{0}) | {1} |".format(name, text) for name, text, _ in COMMANDS]
    out.append("")
    for name, _, module_name in COMMANDS:
        module = importlib.import_module("interlock.cli." + module_name)
        command = sub.choices[name]
        out += ["## `interlock {}`".format(name), ""]
        out += _fence_examples((module.__doc__ or "").strip())
        out += ["", "```text"]
        usage = io.StringIO()
        command.print_usage(usage)
        out.append(usage.getvalue().strip())
        for action in command._actions:
            if action.dest == "help" or isinstance(action, argparse._SubParsersAction):
                continue
            out.append("  {:<26} {}".format(", ".join(action.option_strings) or action.dest,
                                            action.help or ""))
        for action in command._actions:
            if isinstance(action, argparse._SubParsersAction):
                for child in action.choices.values():
                    usage = io.StringIO()
                    child.print_usage(usage)
                    out.append(usage.getvalue().strip())
        out += ["```", ""]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("{} is stale; run python scripts/gen_cli_reference.py".format(OUT))
            return 1
        print("{} is up to date".format(OUT))
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote {}".format(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
